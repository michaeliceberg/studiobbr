import postgres from 'postgres'

const BEHA = 1, VLAD = 2
const GROUPS = [
    [BEHA, 'Стрижки', [['Мужская стрижка', 60, 2000], ['Детская стрижка до 12 лет', 60, 1600], ['Стрижка машинкой', 30, 1600], ['Стрижка машинкой FADE', 45, 1600], ['Стрижка БРО + БРО', 120, 3600]]],
    [BEHA, 'Комплексные услуги', [['Комплекс классическая стрижка + моделирование бороды', 90, 3000], ['Комплекс классическая стрижка + стрижка бороды', 90, 2700], ['Отец и сын', 105, 3100]]],
    [BEHA, 'Оформление бороды и усов', [['Моделирование бороды', 45, 1600], ['Стрижка бороды', 30, 1300]]],
    [BEHA, 'Срочный выход', [['Срочная стрижка', 5, 600]]],
    [BEHA, 'Дополнительные услуги', [['Тонировка бороды', 15, 900], ['Тонировка волос', 15, 1200], ['Удаление воском', 5, 300]]],
    [VLAD, 'Знакомство с мастером: приведи себя в порядок выгодно', [['Мужская стрижка', 60, 1000], ['Мужская стрижка + моделирование бороды', 60, 1600], ['Стрижка под насадку (одна насадка)', 60, 500], ['Детская стрижка (до 11 лет включительно)', 60, 700], ['Бритьё шейвером', 60, 700]]],
]
const sql = postgres(process.env.DATABASE_URL, { max: 1, onnotice: () => {} })
const [{ n }] = await sql`SELECT count(*)::int AS n FROM services WHERE name NOT LIKE 'Тест%'`
if (n > 0) console.log('услуги уже есть:', n)
else {
    let sort = 0
    for (const [staff_id, category, list] of GROUPS) for (const [name, duration_min, price] of list) {
        sort += 10
        await sql`INSERT INTO services ${sql({ staff_id, category, name, duration_min, price, sort })}`
    }
    console.log('добавлено услуг:', sort / 10)
}
await sql.end()
